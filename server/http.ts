export class HttpError extends Error {
  constructor(
    readonly status: number,
    message: string,
  ) {
    super(message);
  }
}

export const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), {
    status,
    headers: { 'content-type': 'application/json', 'cache-control': 'no-store' },
  });

export function errorResponse(err: unknown): Response {
  if (err instanceof HttpError) return json({ error: err.message }, err.status);
  const e = err as Error;
  if (e?.name === 'ChallengeTodo') return json({ error: e.message, todo: true }, 501);
  console.error('[api]', err);
  return json({ error: e?.message ?? 'Unknown server error' }, 500);
}

/** jobIds are generated by the browser with crypto.randomUUID(). */
export function assertJobId(jobId: unknown): string {
  if (typeof jobId !== 'string' || !/^[a-zA-Z0-9-]{8,64}$/.test(jobId)) {
    throw new HttpError(400, 'Invalid jobId');
  }
  return jobId;
}

export const ghoulPath = (uid: string, jobId: string, file: string) => `ghouls/${uid}/${jobId}/${file}`;
